import { writeFileSync } from "node:fs";

const url = process.env.BLOOM_SERVER_URL ?? "";
if (!url) {
  console.warn("BLOOM_SERVER_URL is not set; the client will fall back to its own origin.");
}

writeFileSync(
  "public/config.js",
  `// Generated by scripts/write-client-config.mjs. Do not edit by hand.\n` +
    `// Set BLOOM_SERVER_URL in the Vercel project to point the client at the EC2 server.\n` +
    `window.BLOOM_SERVER_URL = '${url}';\n`,
);
